import { test, expect } from '@playwright/test'
import { register, setupTrip, addExpense } from './helpers'

test('two isolated phones share a private trip, concurrent and persisted offline additions, deletion, and account privacy', async ({ browser, baseURL }) => {
  const a = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 } })
  const b = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 } })
  const c = await browser.newContext({ baseURL, viewport: { width: 1280, height: 900 } })
  const first = await a.newPage(); const second = await b.newPage(); const stranger = await c.newPage()
  const unique = crypto.randomUUID()
  try {
    await register(first, `first-${unique}@example.test`)
    await setupTrip(first)
    await expect(first.getByText('Synchronisé', { exact: true })).toBeVisible()
    await first.getByRole('button', { name: 'Réglages', exact: true }).click()
    await first.getByRole('button', { name: 'Créer une invitation' }).click()
    const invitation = await first.getByLabel('Lien à partager').inputValue()
    await register(second, `second-${unique}@example.test`)
    await second.getByText('Rejoindre le voyage d’un compagnon', { exact: true }).click()
    await second.getByLabel('Lien ou code d’invitation').fill(invitation)
    await second.getByRole('button', { name: 'Rejoindre', exact: true }).click()
    await expect(second.getByRole('navigation', { name: 'Navigation principale' })).toBeVisible()
    await first.getByRole('button', { name: 'Budget', exact: true }).click()
    await Promise.all([addExpense(first, '10,10', 'Téléphone A'), addExpense(second, '20,20', 'Téléphone B')])
    await expect(first.locator('.expense-list')).toContainText('Téléphone B')
    await expect(second.locator('.expense-list')).toContainText('Téléphone A')
    await expect(first.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('30,30')
    // A companion can correct another member's expense without changing its original author.
    await second.getByRole('button', { name: 'Modifier Téléphone A', exact: true }).click()
    await second.getByLabel('Montant (€)', { exact: true }).fill('11,11')
    await second.getByRole('button', { name: 'Enregistrer la modification', exact: true }).click()
    await expect(first.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('31,31')
    // Global budget changes are shared as well as expense rows.
    await first.getByRole('button', { name: 'Réglages', exact: true }).click()
    await first.getByLabel('Budget global sur place (€)').fill('1200')
    await first.getByRole('button', { name: 'Enregistrer le voyage', exact: true }).click()
    await expect(second.locator('.stat').filter({ hasText: /^Budget global/ })).toContainText('1 200,00')
    await first.getByRole('button', { name: 'Budget', exact: true }).click()
    // The application server remains accessible, while Firestore is unreachable.
    // This allows a true reload to prove that the SDK's offline write queue is persisted.
    await b.route('http://127.0.0.1:8080/**', route => route.abort())
    await second.evaluate(async () => {
      const f = await import('/src/firebase.ts')
      await f.setEmulatorNetworkEnabled(false)
    })
    await addExpense(second, '3,45', 'Dépense sans réseau')
    await expect(second.getByText('En attente de synchronisation', { exact: true })).toBeVisible()
    await expect(first.locator('.expense-list')).not.toContainText('Dépense sans réseau')
    await second.reload()
    await expect(second.locator('.expense-list')).toContainText('Dépense sans réseau')
    await b.unroute('http://127.0.0.1:8080/**')
    await second.reload()
    await expect(first.locator('.expense-list')).toContainText('Dépense sans réseau', { timeout: 30_000 })
    await expect(second.getByText('Synchronisé', { exact: true })).toBeVisible()
    first.once('dialog', dialog => dialog.accept())
    await first.getByRole('button', { name: 'Supprimer Téléphone B', exact: true }).click()
    await expect(second.locator('.expense-list')).not.toContainText('Téléphone B')
    await second.reload()
    await expect(second.locator('.expense-list')).not.toContainText('Téléphone B')
    await expect(second.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('14,56')
    await register(stranger, `stranger-${unique}@example.test`)
    await expect(stranger.getByRole('navigation', { name: 'Navigation principale' })).toHaveCount(0)
    await expect(stranger.getByLabel('Voyage actif')).toHaveCount(0)
    await expect(stranger.locator('.expense-list')).toHaveCount(0)
  } finally { await Promise.allSettled([a.close(), b.close(), c.close()]) }
})
