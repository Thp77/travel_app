import { test, expect } from '@playwright/test'
import { setupTrip, addExpense } from './helpers'

test('new traveler, precise amounts, edit, deletion, filters, and reload persistence', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Préparer mon voyage' })).toBeVisible()
  await expect(page.locator('.expense-list')).toHaveCount(0)
  await setupTrip(page)
  await addExpense(page, '12,35', 'Marché', 'Courses')
  await addExpense(page, '20', 'Dîner')
  await expect(page.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('32,35')
  await page.getByRole('button', { name: 'Modifier Marché', exact: true }).click()
  await page.getByLabel('Montant (€)', { exact: true }).fill('15,10')
  await page.getByRole('button', { name: 'Enregistrer la modification' }).click()
  await expect(page.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('35,10')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Supprimer Marché', exact: true }).click()
  await expect(page.locator('.expense-list')).not.toContainText('Marché')
  await page.reload()
  await expect(page.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('20,00')
  await expect(page.locator('.stat.daily')).toContainText('46,66')
  await page.getByLabel('Filtrer par catégorie').selectOption('Courses')
  await expect(page.locator('.expense-list li')).toHaveCount(0)
  await page.getByLabel('Filtrer par catégorie').selectOption('Repas')
  await expect(page.locator('.expense-list li')).toHaveCount(1)
  await page.getByRole('button', { name: 'Étapes', exact: true }).click()
  await page.getByRole('button', { name: 'Terminer cette étape' }).click()
  await page.getByRole('button', { name: 'Budget', exact: true }).click()
  await expect(page.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('20,00')
  assertNoErrors(errors)
})
test('negative or fractional-cent amounts are rejected without changing the budget', async ({ page }) => {
  await page.goto('/'); await setupTrip(page)
  await page.getByLabel('Montant (€)', { exact: true }).fill('-5')
  await page.getByRole('button', { name: 'Enregistrer la dépense', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('montant positif')
  await page.getByLabel('Montant (€)', { exact: true }).fill('0,001')
  await page.getByRole('button', { name: 'Enregistrer la dépense', exact: true }).click()
  await expect(page.locator('.expense-list li')).toHaveCount(0)
})
test('installed application opens, records and reloads an expense entirely offline', async ({ page, context }) => {
  await page.goto('/'); await setupTrip(page)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBeTruthy()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('Hors connexion · sur cet appareil', { exact: true })).toBeVisible()
  await addExpense(page, '1,25', 'Hors réseau')
  await page.reload()
  await expect(page.locator('.expense-list')).toContainText('Hors réseau')
  await expect(page.locator('.stat').filter({ hasText: /^Dépensé/ })).toContainText('1,25')
})
test('320px mobile and desktop layouts fit, real category chart and export', async ({ page }, testInfo) => {
  await page.goto('/'); await setupTrip(page)
  await addExpense(page, '100', 'Hôtel', 'Logement')
  await addExpense(page, '25', 'Restaurant')
  await page.setViewportSize({ width: 320, height: 740 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('mobile.png'), fullPage: true })
  await expect(page.locator('.donut')).toHaveAttribute('style', /80%/)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Réglages', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exporter ma sauvegarde' }).click()
  expect((await download).suggestedFilename()).toMatch(/^travel-app-.*\.json$/)
})
function assertNoErrors(errors: string[]) { expect(errors).toEqual([]) }
